"""TC-SELL-017: a proforma posts nothing and does not follow the order afterwards."""
import pathlib, sys; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from _sell import *

c = Check("tc_sell_017")
a = admin()
sc = Scene(a, stock="100")
order = new_order(sc, "12", approve=True, line={"unit_price": "84", "discount_percent": "2.5"})
none = a.post(PF, {"proforma_date": today().isoformat()})
c.eq(none[0], 422, "no order chosen is a 422")
before = owed(a, sc.customer["id"])
made = must(a.post(PF, {"sales_order_id": order["id"], "proforma_date": today().isoformat()}), "proforma")
c.ok("PF" in made["proforma_number"] and "PI" not in made["proforma_number"].split("-")[0], "a PF series number", made["proforma_number"])
issued = must(a.post(f"{PF}/{made['id']}/issue", {}), "issue")
c.eq(issued["status"], "ISSUED", "issued")
status, raw = a.raw(f"{PF}/{made['id']}/print")
c.eq(status, 200, "prints")
text = pdf_text(raw)
c.ok("PROFORMA INVOICE" in text, "titled PROFORMA INVOICE")
c.ok("not a tax invoice" in text.lower(), "says it is not a tax invoice")
c.eq(journal(a, made["proforma_number"]), [], "nothing posted")
c.eq(owed(a, sc.customer["id"]), before, "outstanding unchanged")
total = D(issued["grand_total"])
must(a.post(f"{SO}/{order['id']}/cancel", {"reason": "check"}), "cancel order")
after = must(a.get(f"{PF}/{made['id']}"), "proforma read")
c.eq(D(after["grand_total"]), total, "totals unchanged after the order is cancelled")
c.eq(len(after["lines"]), len(issued["lines"]), "lines unchanged")
c.done()
