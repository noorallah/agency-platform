"""TC-CUST-014: a parent buyer with shops; the GST number typed once (API half; the Shop of picker and the Shops tab are screen-only)."""
import pathlib, sys; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from _mst import *
from _col import receipt, closing, position, journal

c = Check("tc_cust_014")
a = api()
t = tag()
g1, g2 = gstin("36"), gstin("29")
def new(code: str, **extra: object) -> tuple[int, object]:
    return a.post(CU, {"code": f"{code}{t}", "name": f"DMart {t}", "customer_type": "BUSINESS", "currency_code": "INR", **extra})
st, parent = new("DMART", gst_number=g1)
c.eq(st, 201, f"parent saved ({message(parent)})")
parent = data(parent)
shops = {}
for code in ("DM-KUK", "DM-MIY", "DM-GAC"):
    st, body = new(code, parent_customer_id=parent["id"])
    c.eq(st, 201, f"{code} saves ({message(body)})")
    shops[code] = data(body)
kuk = must(a.get(f"{CU}/{shops['DM-KUK']['id']}"), "kuk")
c.eq((kuk["gst_number_from_parent"], kuk["gst_number"], kuk["parent_code"]), (True, g1, f"DMART{t}"), "shop's box is blank and takes the parent's number")
dup = new("DMART2", gst_number=g1)
c.ok(dup[0] in (409, 422) and f"DMART{t}" in message(dup[1]), "same number with no parent is refused naming the holder", f"{dup[0]} {message(dup[1])}")
blr = new("DM-BLR", parent_customer_id=parent["id"], gst_number=g2)
c.eq(blr[0], 201, f"shop with its own number ({message(blr[1])})")
shops["DM-BLR"] = data(blr[1])
par = must(a.get(f"{CU}/{parent['id']}"), "parent")
c.eq(par["shop_count"], 4, "the parent has 4 shops")
fam = must(a.get(f"{CU}/{parent['id']}/family"), "family")
c.eq(sorted(m["code"] for m in fam["members"]), sorted([f"DMART{t}", f"DM-KUK{t}", f"DM-MIY{t}", f"DM-GAC{t}", f"DM-BLR{t}"]), "family lists the parent and four shops")
c.eq([m["gst_number_from_parent"] for m in fam["members"] if m["code"] == f"DM-BLR{t}"], [False], "BLR keeps its own number")
c.eq(sum(1 for m in fam["members"] if m["gst_number_from_parent"]), 3, "three shops carry the parent's")
g3 = gstin("36")
st, body = a.put(f"{CU}/{parent['id']}", echo("CustomerUpdate", par, {"addresses": "CustomerAddressInput", "contacts": "CustomerContactInput"}, gst_number=g3, pan_number=g3[2:12]))
c.eq(st, 200, f"parent's number changed ({message(body)})")
c.eq(must(a.get(f"{CU}/{shops['DM-KUK']['id']}"), "kuk")["gst_number"], g3, "the shop is billed under the new number")
c.eq(must(a.get(f"{CU}/{shops['DM-BLR']['id']}"), "blr")["gst_number"], g2, "BLR keeps its own")
deep = new("DEEP", parent_customer_id=shops["DM-KUK"]["id"])
c.ok(deep[0] in (409, 422), "a shop cannot be a parent", f"{deep[0]} {message(deep[1])}")
rm = a.delete(f"{CU}/{parent['id']}")
c.ok(rm[0] in (409, 422) and "4 shop" in message(rm[1]), "deleting the parent of 4 shops is refused", f"{rm[0]} {message(rm[1])}")
gac = must(a.get(f"{CU}/{shops['DM-GAC']['id']}"), "gac")
st, body = a.put(f"{CU}/{gac['id']}", echo("CustomerUpdate", gac, {"addresses": "CustomerAddressInput", "contacts": "CustomerContactInput"}, parent_customer_id=None))
c.eq(st, 200, f"parent cleared ({message(body)})")
gac = must(a.get(f"{CU}/{gac['id']}"), "gac")
c.eq((gac["parent_customer_id"], gac["gst_number"]), (None, None), "no parent and no GST number")
c.done()
