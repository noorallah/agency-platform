"""TC-CUST-001: changing one field leaves everything else alone (API half: an update naming only the phone, then the whole record echoed)."""
import pathlib, sys; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from _mst import *

c = Check("tc_cust_001")
a = api()
d = described(a)
base = dict(code=d["code"], customer_type="BUSINESS", name=d["name"], currency_code="INR")
st, body = a.put(f"{CU}/{d['id']}", {**base, "phone": "+919800000199"})
c.eq(st, 200, f"update naming only the phone ({message(body)})")
got = must(a.get(f"{CU}/{d['id']}"), "reread")
c.eq(got["phone"], "+919800000199", "phone is new")
c.eq(D(got["credit_limit"]), D(50000), "credit limit unchanged")
c.eq(got["payment_terms_days"], 30, "payment terms unchanged")
c.eq(D(got["default_discount_percent"]), D("7.5"), "standing discount unchanged")
c.eq(got["customer_group_id"], d["customer_group_id"], "segment unchanged")
c.eq([x["address_line1"] for x in got["addresses"]], ["12 Fixture Street"], "address kept")
c.eq([x["name"] for x in got["contacts"]], ["Fixture Contact"], "contact kept")
c.eq(D(got["current_outstanding"]), D(0), "outstanding unchanged")
whole = echo("CustomerUpdate", got, {"addresses": "CustomerAddressInput", "contacts": "CustomerContactInput"}, phone="+919800000150")
st, body = a.put(f"{CU}/{d['id']}", whole)
c.eq(st, 200, f"whole-record update ({message(body)})")
got2 = must(a.get(f"{CU}/{d['id']}"), "reread")
c.eq((got2["phone"], D(got2["credit_limit"]), got2["payment_terms_days"], len(got2["addresses"]), len(got2["contacts"])), ("+919800000150", D(50000), 30, 1, 1), "whole-record edit keeps the rest")
c.done()
