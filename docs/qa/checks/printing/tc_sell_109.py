"""TC-SELL-109: /print/paper says which paper, and paper= switches one print."""
import pathlib, sys; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from _prt import *

c = Check("tc_sell_109")
a = admin()
sc = Scene(a, stock="200")
cust_b = sc.new_customer()
with counter(a):
    with template(a, page_size="A4"):
        sc.set_paper(cust_b, "HALF")
        bill_b = sc.bill(customer=cust_b)
        got = must(a.get(f"{SI}/{bill_b['id']}/print/paper"), "paper")
        c.eq((got["firm_paper"], got["paper"], got["may_choose"]), ("A4", "A4", False), "step 1: an A4 firm: A4, nothing to choose")
        c.eq(got["customer_paper"], None, "step 1: the customer's half page is not offered on an A4 firm")
        c.eq(set(kinds(printed(a, bill_b["id"]))), {"A4"}, "step 1: prints full pages")
        status, raw = a.raw(f"{SI}/{bill_b['id']}/print?paper=HALF")
        c.eq(status, 422, "paper=HALF on an A4 firm is refused")
        c.ok("chosen at printing only where the firm prints" in refusal_of(raw), "the refusal says why", refusal_of(raw))
        c.eq(a.raw(f"{SI}/{bill_b['id']}/print?paper=A4")[0], 200, "paper=A4 on an A4 firm is fine")
        c.eq(a.raw(f"{SI}/{bill_b['id']}/print?paper=A5")[0], 422, "paper=A5 is not a choice")
    with template(a, page_size="HALF"):
        bill_a = sc.bill()
        got = must(a.get(f"{SI}/{bill_a['id']}/print/paper"), "paper")
        c.eq((got["firm_paper"], got["paper"], got["fits_half_page"], got["may_choose"]), ("HALF", "HALF", True, True), "step 2: a half-page firm offers the choice")
        c.eq(set(kinds(printed(a, bill_a["id"]))), {"HALF"}, "step 2: prints half pages")
        c.eq(set(kinds(printed(a, bill_a["id"], "?paper=A4"))), {"A4"}, "step 3: paper=A4 prints full pages")
        c.eq(set(kinds(printed(a, bill_a["id"]))), {"HALF"}, "step 4: the choice was for that print alone")
        got = must(a.get(f"{SI}/{bill_b['id']}/print/paper"), "paper")
        c.eq((got["customer_paper"], got["paper"], got["may_choose"]), ("HALF", "HALF", True), "B set to half: half")
        sc.set_paper(cust_b, "A4")
        got = must(a.get(f"{SI}/{bill_b['id']}/print/paper"), "paper")
        c.eq((got["customer_paper"], got["paper"], got["may_choose"]), ("A4", "A4", True), "step 5: B on A4: full page, still a choice")
        c.eq(set(kinds(printed(a, bill_b["id"]))), {"A4"}, "step 5: prints full pages")
        c.eq(set(kinds(printed(a, bill_b["id"], "?paper=HALF"))), {"HALF"}, "step 6: paper=HALF prints half pages")
        long_a = sc.bill(lines=60)
        got = must(a.get(f"{SI}/{long_a['id']}/print/paper"), "paper")
        c.eq((got["paper"], got["fits_half_page"], got["may_choose"]), ("A4", False, False), "step 7: sixty lines: full page, nothing to choose")
        c.eq(set(kinds(printed(a, long_a["id"], "?paper=HALF"))), {"A4"}, "step 7: asking half for a long bill still prints full")
        c.eq(a.raw(f"{SI}/{bill_a['id']}/print?paper=junk")[0], 422, "a paper that is neither is refused")
        status, run = post_raw(a, f"{SI}/bulk-print", {"invoice_ids": [bill_a["id"], bill_b["id"]]})
        c.eq(kinds(run), ["HALF"] * 3 + ["A4"] * 3, "step 9: one file, A on half, B on full")
c.done()
